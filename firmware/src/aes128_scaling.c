static void copy_words(u32 *dst, const u32 *src, u32 count)
{
    u32 i;
    for (i = 0; i < count; ++i) dst[i] = src[i];
}

/* Preserve the four NIST plaintext blocks for block indices 0..3. For longer
   messages, repeat the four-block pattern and XOR a group index so each group
   is distinct while remaining deterministic and independently reproducible. */
static u32 plaintext_byte(u32 block, u32 byte_index)
{
    u32 seed_index = ((block & 3u) << 4) + byte_index;
    u32 group_mask = (block >> 2) & 0xffu;
    return plaintext_seed[seed_index] ^ group_mask;
}

static u32 xtime(u32 x)
{
    x &= 0xffu;
    return (((x << 1) & 0xffu) ^ ((x & 0x80u) ? 0x1bu : 0u));
}

static void key_expand(u32 round_key[176])
{
    u32 i, bytes = 16u, r = 1u;
    u32 t0, t1, t2, t3;
    for (i = 0; i < 16u; ++i) round_key[i] = key[i];
    while (bytes < 176u) {
        t0 = round_key[bytes - 4u];
        t1 = round_key[bytes - 3u];
        t2 = round_key[bytes - 2u];
        t3 = round_key[bytes - 1u];
        if ((bytes & 15u) == 0u) {
            u32 old = t0;
            t0 = sbox[t1] ^ rcon[r++];
            t1 = sbox[t2];
            t2 = sbox[t3];
            t3 = sbox[old];
        }
        round_key[bytes] = (round_key[bytes - 16u] ^ t0) & 0xffu; ++bytes;
        round_key[bytes] = (round_key[bytes - 16u] ^ t1) & 0xffu; ++bytes;
        round_key[bytes] = (round_key[bytes - 16u] ^ t2) & 0xffu; ++bytes;
        round_key[bytes] = (round_key[bytes - 16u] ^ t3) & 0xffu; ++bytes;
    }
}

static void add_round_key(u32 state[16], const u32 *round_key)
{
    u32 i;
    for (i = 0; i < 16u; ++i) state[i] = (state[i] ^ round_key[i]) & 0xffu;
}

static void sub_bytes(u32 state[16])
{
    u32 i;
    for (i = 0; i < 16u; ++i) state[i] = sbox[state[i]];
}

static void shift_rows(u32 s[16])
{
    u32 t[16];
    t[0]=s[0]; t[1]=s[5]; t[2]=s[10]; t[3]=s[15];
    t[4]=s[4]; t[5]=s[9]; t[6]=s[14]; t[7]=s[3];
    t[8]=s[8]; t[9]=s[13]; t[10]=s[2]; t[11]=s[7];
    t[12]=s[12]; t[13]=s[1]; t[14]=s[6]; t[15]=s[11];
    copy_words(s, t, 16u);
}

static void mix_columns(u32 s[16])
{
    u32 c;
    for (c = 0; c < 4u; ++c) {
        u32 i = c << 2;
        u32 a0=s[i], a1=s[i+1], a2=s[i+2], a3=s[i+3];
        u32 all = a0 ^ a1 ^ a2 ^ a3;
        s[i]   = (a0 ^ all ^ xtime(a0 ^ a1)) & 0xffu;
        s[i+1] = (a1 ^ all ^ xtime(a1 ^ a2)) & 0xffu;
        s[i+2] = (a2 ^ all ^ xtime(a2 ^ a3)) & 0xffu;
        s[i+3] = (a3 ^ all ^ xtime(a3 ^ a0)) & 0xffu;
    }
}

static void aes_encrypt_block(const u32 input[16], u32 output[16], const u32 round_key[176])
{
    u32 state[16];
    u32 round;
    copy_words(state, input, 16u);
    add_round_key(state, round_key);
    for (round = 1u; round < 10u; ++round) {
        sub_bytes(state);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, round_key + (round << 4));
    }
    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, round_key + 160u);
    copy_words(output, state, 16u);
}

static void increment_counter(u32 counter[16])
{
    u32 i = 16u;
    while (i != 0u) {
        --i;
        counter[i] = (counter[i] + 1u) & 0xffu;
        if (counter[i] != 0u) break;
    }
}

static void run_mode(const u32 round_key[176])
{
    u32 block, i;
    u32 in[16], out[16], chain[16], stream[16];
#if EXP_G_MODE == 2 || EXP_G_MODE == 3
    copy_words(chain, iv, 16u);
#elif EXP_G_MODE == 4
    copy_words(chain, initial_counter, 16u);
#endif
    for (block = 0; block < BLOCKS; ++block) {
        for (i = 0; i < 16u; ++i) in[i] = plaintext_byte(block, i);
#if EXP_G_MODE == 1
        aes_encrypt_block(in, out, round_key);
#elif EXP_G_MODE == 2
        for (i = 0; i < 16u; ++i) in[i] ^= chain[i];
        aes_encrypt_block(in, out, round_key);
        copy_words(chain, out, 16u);
#elif EXP_G_MODE == 3
        aes_encrypt_block(chain, stream, round_key);
        for (i = 0; i < 16u; ++i) out[i] = (in[i] ^ stream[i]) & 0xffu;
        copy_words(chain, out, 16u);
#else
        aes_encrypt_block(chain, stream, round_key);
        for (i = 0; i < 16u; ++i) out[i] = (in[i] ^ stream[i]) & 0xffu;
        increment_counter(chain);
#endif
        for (i = 0; i < 16u; ++i) exp_g_output[(block << 4) + i] = out[i];
    }
}

int main(void)
{
    u32 round_key[176];
    u32 i, errors = 0u;
    u32 checksum = 2166136261u;
    *start_reg = 0x47110000u | EXP_G_MODE;
    key_expand(round_key);
    run_mode(round_key);
    *stop_reg = 0x47220000u | EXP_G_MODE;
    for (i = 0; i < PAYLOAD_BYTES; ++i) {
        checksum ^= exp_g_output[i] & 0xffu;
        checksum *= 16777619u;
    }
    if (checksum != EXP_G_EXPECTED_FNV) ++errors;
    exp_g_errors = errors;
    *errors_reg = errors;
    *status_reg = (errors == 0u) ? PASS_WORD : FAIL_WORD;
    return 0;
}
