                        expected_byte[i*16+8], expected_byte[i*16+9], expected_byte[i*16+10], expected_byte[i*16+11],
                        expected_byte[i*16+12], expected_byte[i*16+13], expected_byte[i*16+14], expected_byte[i*16+15]);
                end
                #100;
                $finish;
            end
        end
    end

